"""## 2. Carregamento e Preparação dos Dados Brutos para o Pipeline"""

# Carregamento da base de dados original
df = pd.read_csv('Obesity.csv')
print('DataFrame "df" carregado com sucesso!')

# Criar uma cópia para o pipeline, removendo duplicatas e mapeando o alvo
df_raw_for_pipeline = df.copy()
df_raw_for_pipeline.drop_duplicates(inplace=True)
print(f"Linhas duplicadas removidas. Novo número de linhas: {df_raw_for_pipeline.shape[0]}")

# Mapear a variável alvo 'Obesity' para valores numéricos (0-6)
obesity_mapping_for_pipeline = {
    'Insufficient_Weight': 0,
    'Normal_Weight': 1,
    'Overweight_Level_I': 2,
    'Overweight_Level_II': 3,
    'Obesity_Type_I': 4,
    'Obesity_Type_II': 5,
    'Obesity_Type_III': 6
}
df_raw_for_pipeline['Obesity'] = df_raw_for_pipeline['Obesity'].map(obesity_mapping_for_pipeline)

# Definir X_raw e y_raw para o pipeline. O 'preprocessor' cuidará das features.
X_raw = df_raw_for_pipeline.drop('Obesity', axis=1)
y_raw = df_raw_for_pipeline['Obesity']

print("\nX_raw e y_raw criados para o pipeline completo.")
print("Shape de X_raw:", X_raw.shape)
print("Shape de y_raw:", y_raw.shape)
display(X_raw.head())
display(y_raw.head())

"""## 3. Divisão entre Treino e Teste (Dados Brutos)"""

# Dividir X_raw e y_raw em conjuntos de treino e teste
X_train_raw, X_test_raw, y_train_raw, y_test_raw = train_test_split(
    X_raw, y_raw, test_size=0.2, random_state=42, stratify=y_raw
)

print(f"Shape de X_train_raw: {X_train_raw.shape}")
print(f"Shape de X_test_raw: {X_test_raw.shape}")
print(f"Shape de y_train_raw: {y_train_raw.shape}")
print(f"Shape de y_test_raw: {y_test_raw.shape}")

"""## 4. Definição, Treinamento e Salvamento do Pipeline de Machine Learning"""

print("##### Construindo o Pipeline Completo com Pré-processador #####")

# Re-definir o preprocessor, pois as features cruas precisam dele
original_numerical_features = ['Age', 'Height', 'Weight', 'FCVC', 'NCP', 'CH2O', 'FAF', 'TUE']
original_categorical_features = ['Gender', 'family_history', 'FAVC', 'CAEC', 'SMOKE', 'SCC', 'CALC', 'MTRANS']

preprocessor = ColumnTransformer(
    transformers=[
        ("num", StandardScaler(), original_numerical_features),
        ("cat", OneHotEncoder(handle_unknown="ignore"), original_categorical_features)
    ],
    remainder='passthrough'
)

# Construir o Pipeline completo
pipeline_completo = Pipeline(
    steps=[
        ("preprocessor", preprocessor),
        ("classifier", RandomForestClassifier(random_state=42))
    ]
)

print("Pipeline completo (preprocessor + RandomForestClassifier) definido com sucesso!")

# Treinar o Pipeline completo com X_raw e y_raw
# O pipeline_completo se encarregará de fazer todo o pré-processamento internamente.
print("\nTreinando o pipeline completo com dados brutos (X_train_raw, y_train_raw)...")
pipeline_completo.fit(X_train_raw, y_train_raw)
print("Pipeline completo treinado com sucesso!")

# Avaliar a funcionalidade do pipeline
print("\nAvaliando o pipeline no conjunto de teste...")
y_pred_raw = pipeline_completo.predict(X_test_raw)

accuracy_raw = accuracy_score(y_test_raw, y_pred_raw)
print(f"Acurácia do pipeline completo: {accuracy_raw:.4f}")

print("\nRelatório de Classificação do pipeline completo:\n")
print(classification_report(y_test_raw, y_pred_raw))

conf_matrix_raw = confusion_matrix(y_test_raw, y_pred_raw)
plt.figure(figsize=(10, 8))
sns.heatmap(
    conf_matrix_raw, annot=True, fmt='d', cmap='Blues',
    xticklabels=[str(i) for i in pipeline_completo.named_steps['classifier'].classes_],
    yticklabels=[str(i) for i in pipeline_completo.named_steps['classifier'].classes_]
)
plt.title('Matriz de Confusão do Pipeline Completo')
plt.xlabel('Previsão')
plt.ylabel('Real')
plt.show()

# Salvar o Pipeline completo como 'pipeline_obesity_final.pkl' (conforme solicitação do usuário)
joblib.dump(pipeline_completo, "pipeline_obesity_final.pkl")
print("\nPipeline completo salvo com sucesso como 'pipeline_obesity_final.pkl'!")



